import { writeFile, mkdir } from 'node:fs/promises';
import openapiTS, { astToString } from 'openapi-typescript';
import { learnerOpenApi } from '../contracts/dist/learner-openapi.js';

await mkdir(new URL('./src/', import.meta.url), { recursive: true });
await writeFile(new URL('./openapi.json', import.meta.url), JSON.stringify(learnerOpenApi, null, 2) + '\n');
await writeFile(new URL('./src/schema.ts', import.meta.url), '// Generated by pnpm --filter @medical-device/api-client generate.\n' + astToString(await openapiTS(learnerOpenApi)));
