import assert from 'node:assert/strict';
import {validateMediaActivity,validateCourseForPublication} from '../packages/simulation-schema/dist/index.js';
const assets=[{assetVersionId:'image:1',sourceType:'image',contentType:'image/png'},{assetVersionId:'video:1',sourceType:'video',contentType:'video/mp4'}];
const image={type:'image',media:{assetVersionId:'image:1',altText:'A closed safety cover.'}};
const video={type:'video',media:{assetVersionId:'video:1',transcript:'Identify the cover before opening it.'}};
const original=JSON.stringify({assets,image,video});
assert.equal(validateMediaActivity(image,assets).valid,true);
assert.equal(validateMediaActivity(video,assets).valid,true);
const rejects=(value,code,list=assets)=>assert(validateMediaActivity(value,list).findings.some(f=>f.code===code),code);
rejects({...image,media:{...image.media,url:'https://unapproved.test/a.png'}},'MEDIA_BINDING_INVALID');
rejects({...image,media:{...image.media,assetVersionId:'https://unapproved.test/a.png'}},'MEDIA_BINDING_INVALID');
rejects(image,'MEDIA_ASSET_NOT_APPROVED',[]);
rejects(image,'MEDIA_ASSET_NOT_APPROVED',[...assets,assets[0]]);
rejects({...image,media:{...image.media,assetVersionId:'video:1'}},'MEDIA_ASSET_TYPE_INVALID');
rejects(image,'MEDIA_ASSET_TYPE_INVALID',[{...assets[0],contentType:'image/svg+xml'}]);
rejects(image,'MEDIA_ASSET_TYPE_INVALID',[{...assets[0],sourceType:'pdf'}]);
rejects({...image,media:{...image.media,altText:' '}},'MEDIA_ALT_REQUIRED');
rejects({...image,media:{...image.media,altText:'x'.repeat(2001)}},'MEDIA_ALT_REQUIRED');
rejects({...video,media:{assetVersionId:'video:1'}},'MEDIA_TRANSCRIPT_REQUIRED');
rejects({...video,media:{...video.media,transcript:'x'.repeat(100001)}},'MEDIA_TRANSCRIPT_REQUIRED');
rejects({...image,media:{...image.media,transcript:'unexpected'}},'MEDIA_FIELD_INVALID');
for(const value of [null,{},[],{type:'image',media:null}])assert.equal(validateMediaActivity(value,assets).valid,false);
const publication=validateCourseForPublication({course:{modules:[{activities:[image,video]}]},approvedSourceArtifactIds:[],approvedMediaAssets:assets});
assert.equal(publication.findings.some(f=>f.code.startsWith('MEDIA_')),false);
assert.equal(publication.findings.some(f=>f.code==='MEDIA_ASSET_NOT_APPROVED'),false);
assert.equal(JSON.stringify({assets,image,video}),original,'Validation mutated inputs');
console.log('Media contract passed: private version binding, approved type/format, descriptions/transcripts, strict fields, nonmutation and publication validation.');
