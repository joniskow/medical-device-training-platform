import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readFile } from "node:fs/promises";
import { createGlbModelManifest, validateBrowserModelManifest } from "../packages/model-runtime/dist/index.js";

const modelPath = "fixtures/nxstage-system-one-interactive/nxstage-system-one.glb";
const manifestPath = "fixtures/nxstage-system-one-interactive/model-manifest.json";
const bytes = await readFile(modelPath);
const manifest = JSON.parse(await readFile(manifestPath, "utf8"));
const hash = createHash("sha256").update(bytes).digest("hex");
assert.equal(manifest.sourceHash, hash, "NxStage manifest hash must bind the exported GLB");
const validated = validateBrowserModelManifest(manifest);
assert.equal(validated.fidelity?.status, "VISUAL_RECONSTRUCTION");
assert.equal(validated.fidelity?.scaleStatus, "UNMEASURED");
const panel = validated.components.find((component) => component.componentId === "nxstage-control-panel");
assert.ok(panel, "NxStage control panel component must survive export");
const expectedTargets = ["NX-C01-FLOW", "NX-C01-RATE", "NX-C01-STOP", "NX-C01-MUTE", ...[1,2,3].flatMap(row => [`NX-C01-ROW${row}-DOWN`, `NX-C01-ROW${row}-UP`])];
assert.deepEqual(new Set(panel.interactionTargets?.map((target) => target.targetId)), new Set(expectedTargets));
assert.ok(panel.interactionTargets?.every((target) => target.pressDepthMeters !== undefined && target.pressDepthMeters > 0 && target.pressDepthMeters <= 0.05));
const cycler = validated.components.find((component) => component.componentId === "nxstage-cycler-door");
assert.equal(cycler?.interactionTargets?.find((target) => target.targetId === "NX-C03-CYCLER-DOOR")?.openTranslationMeters, 0.8, "The upper door must retain its bounded sliding interaction");
assert.ok(validated.components.some((component) => component.componentId === "nxstage-cabinet-door"), "The lower cabinet door must survive export");
const structural = createGlbModelManifest(bytes, hash, image => createHash("sha256").update(image).digest("hex"));
assert.equal(structural.meshCount, validated.meshCount);
assert.equal(structural.triangleCount, validated.triangleCount);
assert.equal(structural.textureCount, 49);
assert.ok(structural.textures.every(texture => /^[a-f0-9]{64}$/.test(texture.sha256)));
console.log(`NxStage GLB passed: ${validated.meshCount} meshes, ${validated.triangleCount} triangles, ${structural.textureCount} embedded PBR textures, ${expectedTargets.length} exported press targets, bound hash, and explicit visual-reconstruction uncertainty.`);
